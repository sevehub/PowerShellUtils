<#
.SYNOPSIS
    Creates an Obsidian vault with a dedicated Blog folder and an AI Work Log weekly template.

.DESCRIPTION
    Run once, just before opening Obsidian for the first time. Creates the folder hierarchy
    and a weekly template. The weekly notes themselves (named like 2026-W42.md) are created
    by Obsidian's Daily notes plugin, see Welcome.md for the settings. Existing files are
    never overwritten, so a second run only adds what is missing.

.PARAMETER VaultName
    Name of the vault folder. Defaults to 'MyKnowledgeVault'.

.PARAMETER SetLocal
    Create the vault next to the script instead of in the Documents folder.

.EXAMPLE
    .\Create-ObsidianVault.ps1 -VaultName "SecondBrain"
    Creates the vault in Documents.

.EXAMPLE
    .\Create-ObsidianVault.ps1 -VaultName "WorkVault" -SetLocal
    Creates the vault next to the script.
#>
param (
    [Parameter(HelpMessage = "Name of the Obsidian Vault")]
    [string]$VaultName = "MyKnowledgeVault",

    [Parameter(HelpMessage = "Create the vault in the script folder")]
    [switch]$SetLocal
)

# ---------- helpers ----------

# UTF-8 without BOM, so the YAML front matter is read correctly by Obsidian.
function Write-Utf8NoBom {
    param ([string]$Path, [string]$Content)
    [System.IO.File]::WriteAllText($Path, $Content, (New-Object System.Text.UTF8Encoding($false)))
}

# ---------- root path ----------
if ($SetLocal) {
    # $PSScriptRoot is the directory where the .ps1 file is located
    $BaseDir = $PSScriptRoot
    if ([string]::IsNullOrWhiteSpace($BaseDir)) {
        # Fallback if the script is run as a selection in some consoles
        $BaseDir = Get-Location
    }
} else {
    $BaseDir = Join-Path $HOME "Documents"
}
$RootPath = Join-Path $BaseDir $VaultName

Write-Host "`n--- Obsidian Vault Initializer ---" -ForegroundColor Cyan
Write-Host "Target Location: $RootPath" -ForegroundColor White

# ---------- folder structure ----------
$Folders = @(
    "00_Inbox",              # Quick notes, raw thoughts, unsorted ideas
    "10_Blog/Drafts",        # Dedicated Blog area: Vim -> Typst pipeline
    "10_Blog/Published",     # Posts that are live
    "20_AI_Worklog/Weekly",  # One note per ISO week, created by Obsidian (YYYY-Www.md)
    "30_Knowledge",          # Permanent Zettelkasten/Wiki/Atlas
    "40_Projects",           # Active projects
    "50_Archive",            # Completed projects and old notes
    "Attachments",           # Images, PDFs, and assets
    "Templates"              # Reusable Markdown structures
)

if (!(Test-Path $RootPath)) {
    try {
        New-Item -ItemType Directory -Path $RootPath -ErrorAction Stop | Out-Null
        Write-Host "[+] Root directory created." -ForegroundColor Green
    } catch {
        Write-Error "Failed to create root directory: $($_.Exception.Message)"
        return
    }
} else {
    Write-Host "[!] Root directory already exists. Adding missing subfolders..." -ForegroundColor Yellow
}

foreach ($Folder in $Folders) {
    $FolderPath = Join-Path $RootPath $Folder
    if (!(Test-Path $FolderPath)) {
        New-Item -ItemType Directory -Path $FolderPath -Force | Out-Null
        Write-Host "  [+] Created: $Folder" -ForegroundColor Green
    }
}

# ---------- weekly template (never overwritten) ----------
$TemplateFile = Join-Path $RootPath "Templates/AI-Worklog-Weekly.md"
if (!(Test-Path $TemplateFile)) {
    $TemplateContent = @'
# AI Work Log {{date:GGGG-[W]WW}}

Weekly tally generated by the AI Work Log app. Paste it below.

## Tally


## Notes

'@
    Write-Utf8NoBom -Path $TemplateFile -Content $TemplateContent
    Write-Host "  [+] Created: Templates/AI-Worklog-Weekly.md" -ForegroundColor Green
}

# ---------- welcome file (never overwritten) ----------
$WelcomeFile = Join-Path $RootPath "Welcome.md"
if (!(Test-Path $WelcomeFile)) {
    $WelcomeContent = @"
# Welcome to your Vault: $VaultName

This vault was created via PowerShell to ensure 1:1 alignment with Vim.

## Quick Start
- Use ``00_Inbox`` for raw thoughts.
- Use ``10_Blog/Drafts`` for your Typst-Vim9Script pipeline, and ``10_Blog/Published`` for live posts.
- Use ``20_AI_Worklog/Weekly`` for the AI Work Log tally, one note per ISO week.
- Store all images in ``Attachments``.

## Weekly note setup
Settings > Core plugins > enable Daily notes, then set:
- Date format: ``GGGG-[W]WW``
- New file location: ``20_AI_Worklog/Weekly``
- Template file location: ``Templates/AI-Worklog-Weekly``

Run the command "Open today's note". The first call in a week creates the note, for example 2026-W42.md, and later calls open the same file.

## Alignment Check
This is a standard Markdown paragraph. No bullets here, so it will look exactly the same in Vim and Obsidian.
"@
    Write-Utf8NoBom -Path $WelcomeFile -Content $WelcomeContent
}

Write-Host "`nSuccess! You can now start adding .md files using Vim." -ForegroundColor Cyan
Write-Host "First time in Obsidian: 'Open folder as vault' -> $RootPath" -ForegroundColor Yellow
Write-Host "Then follow 'Weekly note setup' in Welcome.md." -ForegroundColor Yellow
Write-Host "----------------------------------`n"
